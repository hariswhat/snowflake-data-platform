-- Schemas and access roles inside RIDGELINE_<env>. Run by RL_<env>_DEPLOYER,
-- which owns the database (admin V1.0.2).
--
-- Access roles are database roles: they carry the object privileges and stay
-- with the database, so a clone or a replica brings them along. Functional
-- account roles (admin V1.0.0) are granted access roles, never objects
-- (ADR-0004). Managed access means only the schema owner grants on objects,
-- so an engineer cannot share a table by granting it directly.
CREATE SCHEMA IF NOT EXISTS RAW WITH MANAGED ACCESS COMMENT = 'Files as loaded by Snowpipe, typed, plus the original record';
CREATE SCHEMA IF NOT EXISTS CORE WITH MANAGED ACCESS COMMENT = 'Conformed dimensions and facts; tasks and streams';
CREATE SCHEMA IF NOT EXISTS MART WITH MANAGED ACCESS COMMENT = 'Secure views for BI and analysts';
CREATE SCHEMA IF NOT EXISTS OPS WITH MANAGED ACCESS COMMENT = 'Data quality results, late arrivals, monitoring views';
CREATE SCHEMA IF NOT EXISTS GOVERNANCE WITH MANAGED ACCESS COMMENT = 'Tags, masking and row access policies';

CREATE DATABASE ROLE IF NOT EXISTS AR_RAW_READ;
CREATE DATABASE ROLE IF NOT EXISTS AR_CORE_READ;
CREATE DATABASE ROLE IF NOT EXISTS AR_CORE_WRITE;
CREATE DATABASE ROLE IF NOT EXISTS AR_MART_READ;
CREATE DATABASE ROLE IF NOT EXISTS AR_OPS_READ;

GRANT USAGE ON DATABASE RIDGELINE_{{ env }} TO DATABASE ROLE AR_RAW_READ;
GRANT USAGE ON DATABASE RIDGELINE_{{ env }} TO DATABASE ROLE AR_CORE_READ;
GRANT USAGE ON DATABASE RIDGELINE_{{ env }} TO DATABASE ROLE AR_MART_READ;
GRANT USAGE ON DATABASE RIDGELINE_{{ env }} TO DATABASE ROLE AR_OPS_READ;

GRANT USAGE ON SCHEMA RAW TO DATABASE ROLE AR_RAW_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA RAW TO DATABASE ROLE AR_RAW_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW TO DATABASE ROLE AR_RAW_READ;

GRANT USAGE ON SCHEMA CORE TO DATABASE ROLE AR_CORE_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA CORE TO DATABASE ROLE AR_CORE_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CORE TO DATABASE ROLE AR_CORE_READ;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA CORE TO DATABASE ROLE AR_CORE_READ;
GRANT DATABASE ROLE AR_CORE_READ TO DATABASE ROLE AR_CORE_WRITE;
GRANT INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA CORE TO DATABASE ROLE AR_CORE_WRITE;

GRANT USAGE ON SCHEMA MART TO DATABASE ROLE AR_MART_READ;
GRANT SELECT ON ALL VIEWS IN SCHEMA MART TO DATABASE ROLE AR_MART_READ;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA MART TO DATABASE ROLE AR_MART_READ;

GRANT USAGE ON SCHEMA OPS TO DATABASE ROLE AR_OPS_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA OPS TO DATABASE ROLE AR_OPS_READ;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA OPS TO DATABASE ROLE AR_OPS_READ;
-- INFORMATION_SCHEMA.TASK_HISTORY (OPS.TASK_FAILURE) returns only tasks the
-- caller's roles own or can monitor.
GRANT MONITOR ON FUTURE TASKS IN SCHEMA CORE TO DATABASE ROLE AR_OPS_READ;

GRANT DATABASE ROLE AR_MART_READ TO ROLE RL_{{ env }}_ANALYST;
GRANT DATABASE ROLE AR_RAW_READ TO ROLE RL_{{ env }}_ENGINEER;
GRANT DATABASE ROLE AR_CORE_WRITE TO ROLE RL_{{ env }}_ENGINEER;
GRANT DATABASE ROLE AR_OPS_READ TO ROLE RL_{{ env }}_ENGINEER;
